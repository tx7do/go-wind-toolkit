// 核心生成逻辑：spec × proto 描述符 → 强类型映射函数。
package main

import (
	"context"
	"fmt"
	"go/format"
	"sort"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
)

// outputFile 一份待落盘的生成物。
type outputFile struct {
	// name 相对输出根的路径（来自 spec.output.file）。
	name string
	// pkg Go 包名。
	pkg string
	// content gofmt 后的源码。
	content []byte
}

// generateAll 编译 spec 涉及的 proto 并逐条生成映射函数。
func generateAll(ctx context.Context, importPaths []string, specs []*Spec) ([]outputFile, error) {
	var protoFiles []string
	seen := make(map[string]bool)
	for _, s := range specs {
		if !seen[s.Message.Proto] {
			seen[s.Message.Proto] = true
			protoFiles = append(protoFiles, s.Message.Proto)
		}
	}

	req, err := loadRequest(ctx, importPaths, protoFiles)
	if err != nil {
		return nil, err
	}
	plugin, err := protogen.Options{}.New(req)
	if err != nil {
		return nil, fmt.Errorf("build proto model: %w", err)
	}

	outs := make([]outputFile, 0, len(specs))
	for _, s := range specs {
		out, err := generateSpec(plugin, s)
		if err != nil {
			return nil, fmt.Errorf("spec %s: %w", s.Source(), err)
		}
		outs = append(outs, *out)
	}
	return outs, nil
}

// fieldEntry 一条已解析的字段映射规则。
type fieldEntry struct {
	fld    *protogen.Field
	target string // 已含限定符的目标名（option）或裸字段名（struct）
	guard  string // 归一化后的卫语句（auto 已推导）
	cast   string
	spread bool // option 风格：以 v... 展开传参
}

func generateSpec(plugin *protogen.Plugin, s *Spec) (*outputFile, error) {
	msg, err := findMessage(plugin, s.Message.Type)
	if err != nil {
		return nil, err
	}

	entries, needsTime, err := resolveEntries(s, msg)
	if err != nil {
		return nil, err
	}

	// 收集导入：conf 包（消息所在）自动声明；time 按需。
	confPath := string(msg.GoIdent.GoImportPath)
	qualifiers := make(map[string]string, len(s.Imports)+2)
	for q, p := range s.Imports {
		qualifiers[q] = p
	}
	confQual := "v1"
	for q, p := range qualifiers {
		if p == confPath {
			confQual = q
		}
	}
	qualifiers[confQual] = confPath
	if needsTime {
		qualifiers["time"] = "time"
	}

	msgType := confQual + "." + msg.GoIdent.GoName
	targetType := s.qualifiedType(s.Message.TargetType)
	doc := strings.TrimSpace(s.Message.Comment)
	if doc == "" {
		doc = strings.TrimSpace(string(msg.Comments.Leading))
	}

	var b strings.Builder
	b.WriteString("// Code generated by protoc-gen-fieldmap. DO NOT EDIT.\n")
	b.WriteString("//\n")
	fmt.Fprintf(&b, "// 来源: %s (%s → %s)，调整映射请编辑对应 spec 后重新生成。\n",
		s.Source(), s.Message.Proto, s.Message.Type)
	b.WriteString("\n")
	fmt.Fprintf(&b, "package %s\n\n", s.Output.Package)

	var body strings.Builder
	switch s.Message.Style {
	case StyleOption:
		writeOptionFunc(&body, s, doc, msgType, targetType, entries)
	case StyleStruct:
		writeStructFunc(&body, s, doc, msgType, targetType, entries)
	default:
		writeFillFunc(&body, s, doc, msgType, targetType, entries)
	}

	// 只保留代码里实际引用过的导入（qualifier 以 "qual." 形式出现），
	// 避免 struct 风格等场景输出未使用的 import。
	used := make(map[string]string, len(qualifiers))
	bodyText := body.String()
	for q, p := range qualifiers {
		if strings.Contains(bodyText, q+".") {
			used[q] = p
		}
	}
	writeImports(&b, used)
	b.WriteString("\n")
	b.WriteString(bodyText)

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w\n%s", err, b.String())
	}
	return &outputFile{
		name:    s.Output.File,
		pkg:     s.Output.Package,
		content: formatted,
	}, nil
}

// resolveEntries 把 spec.fields 解析为按字段号排序的条目，同时校验字段
// 存在性与 guard/cast 对字段类型的适配性。spec 里写了 proto 上不存在的
// 字段名、或对不兼容类型用了 cast/guard，都在这里报错——这正是生成器
// 相对手写映射的第一道防线。
func resolveEntries(s *Spec, msg *protogen.Message) ([]fieldEntry, bool, error) {
	// key（proto 名或 JSON 名）→ 字段。
	index := make(map[string]*protogen.Field, len(msg.Fields))
	for _, f := range msg.Fields {
		index[string(f.Desc.Name())] = f
		index[f.Desc.JSONName()] = f
	}

	entries := make([]fieldEntry, 0, len(s.Message.Fields))
	needsTime := false

	for key, fs := range s.Message.Fields {
		f, ok := index[key]
		if !ok {
			return nil, false, fmt.Errorf("fields[%s]: no such field in %s (available: %s)",
				key, msg.Desc.FullName(), availableFieldNames(msg))
		}
		if fs.Skip {
			continue
		}
		guard, cast, err := resolveFieldKinds(s, key, f, &fs)
		if err != nil {
			return nil, false, err
		}
		if cast == castSeconds || cast == castMillis {
			needsTime = true
		}
		target := fs.Target
		if s.Message.Style == StyleStruct || s.Message.Style == StyleFill {
			if target == "" {
				target = camelTarget(string(f.Desc.Name()))
			}
		} else {
			// option 风格：裸名目标补上缺省包限定符（显式前缀优先）。
			if target != "" && !strings.Contains(target, ".") && s.Message.TargetQualifier != "" {
				target = s.Message.TargetQualifier + "." + target
			}
			target = s.qualifiedType(target)
		}
		entries = append(entries, fieldEntry{fld: f, target: target, guard: guard, cast: cast, spread: fs.Spread})
	}

	sort.SliceStable(entries, func(i, j int) bool {
		return entries[i].fld.Desc.Number() < entries[j].fld.Desc.Number()
	})
	return entries, needsTime, nil
}

// resolveFieldKinds 归一化 guard（auto 按类型推导）并校验 cast 的类型适配性。
func resolveFieldKinds(s *Spec, key string, f *protogen.Field, fs *FieldSpec) (string, string, error) {
	kind := f.Desc.Kind()
	isList := f.Desc.IsList()
	isMap := f.Desc.IsMap()

	isNumeric := false
	isInteger := false
	isString := kind == protoreflect.StringKind
	isBool := kind == protoreflect.BoolKind
	isMessage := f.Message != nil
	isEnum := f.Enum != nil
	switch kind {
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind,
		protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind,
		protoreflect.Uint32Kind, protoreflect.Fixed32Kind,
		protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		isNumeric, isInteger = true, true
	case protoreflect.FloatKind, protoreflect.DoubleKind:
		isNumeric = true
	}

	shape := "singular"
	if isMap {
		shape = "map"
	} else if isList {
		shape = "list"
	}

	guard := fs.Guard
	if guard == guardAuto {
		guard = defaultGuard(shape, isString, isBool, isNumeric, isEnum, isMessage)
	}
	switch guard {
	case guardEmpty:
		if !isString || shape != "singular" {
			return "", "", fmt.Errorf("fields[%s]: guard %q only fits singular string fields (got %s %s)", key, guard, shape, kind)
		}
	case guardZero, guardPositive:
		// bool 允许 zero 卫语句（渲染为 v 本身），positive 仍限数值/枚举。
		if guard == guardPositive && (shape != "singular" || (!isNumeric && !isEnum)) {
			return "", "", fmt.Errorf("fields[%s]: guard %q only fits singular numeric/enum fields (got %s %s)", key, guard, shape, kind)
		}
		if guard == guardZero && (shape != "singular" || (!isNumeric && !isEnum && !isBool)) {
			return "", "", fmt.Errorf("fields[%s]: guard %q only fits singular numeric/enum/bool fields (got %s %s)", key, guard, shape, kind)
		}
	case guardNotNil:
		if shape != "singular" || !isMessage {
			return "", "", fmt.Errorf("fields[%s]: guard %q only fits singular message fields (got %s %s)", key, guard, shape, kind)
		}
	case guardLen:
		if shape != "singular" || kind == protoreflect.BytesKind {
			// repeated / map / bytes。
			break
		}
		return "", "", fmt.Errorf("fields[%s]: guard %q only fits repeated/map/bytes fields (got singular %s)", key, guard, kind)
	}

	if fs.Spread && (!f.Desc.IsList() || f.Desc.IsMap()) {
		return "", "", fmt.Errorf("fields[%s]: spread requires a repeated (list) field", key)
	}

	cast := fs.Cast
	switch cast {
	case "":
		// 原样传递。
	case castSeconds, castMillis:
		if shape != "singular" || !isInteger {
			return "", "", fmt.Errorf("fields[%s]: cast %q only fits singular integer fields (got %s %s)", key, cast, shape, kind)
		}
	case castInt, castInt32, castInt64, castUint, castUint32, castUint64:
		if shape != "singular" || (!isInteger && !isEnum) {
			return "", "", fmt.Errorf("fields[%s]: cast %q only fits singular integer/enum fields (got %s %s)", key, cast, shape, kind)
		}
	case castFloat32, castFloat64:
		if shape != "singular" || (!isNumeric && !isInteger) {
			return "", "", fmt.Errorf("fields[%s]: cast %q only fits singular numeric fields (got %s %s)", key, cast, shape, kind)
		}
	default:
		return "", "", fmt.Errorf("fields[%s]: unsupported cast %q", key, cast)
	}

	return guard, cast, nil
}

// defaultGuard 按字段形状推导缺省卫语句，与 go-wind-bootstrap 适配器的
// 手写习惯一致：字符串判空、数值判零、布尔无条件、消息判 nil、集合判长度。
func defaultGuard(shape string, isString, isBool, isNumeric, isEnum, isMessage bool) string {
	switch shape {
	case "list", "map":
		return guardLen
	case "singular":
		switch {
		case isString:
			return guardEmpty
		case isBool:
			return guardNone
		case isNumeric, isEnum:
			return guardZero
		case isMessage:
			return guardNotNil
		}
	}
	// bytes 等其余类别。
	return guardLen
}

// findMessage 在全部已加载文件（含依赖）中按全名查找消息；spec 里的 Type
// 允许省略 proto 包前缀，按 ".Type" 后缀唯一匹配。
func findMessage(plugin *protogen.Plugin, typ string) (*protogen.Message, error) {
	var found *protogen.Message
	var walk func(m *protogen.Message)
	walk = func(m *protogen.Message) {
		if found != nil {
			return
		}
		full := string(m.Desc.FullName())
		if full == typ || strings.HasSuffix(full, "."+typ) {
			found = m
			return
		}
		for _, nested := range m.Messages {
			walk(nested)
		}
	}
	for _, f := range plugin.Files {
		for _, m := range f.Messages {
			walk(m)
		}
		if found != nil {
			break
		}
	}
	if found == nil {
		return nil, fmt.Errorf("message %q not found in compiled protos", typ)
	}
	return found, nil
}

func availableFieldNames(msg *protogen.Message) string {
	names := make([]string, 0, len(msg.Fields))
	for _, f := range msg.Fields {
		names = append(names, string(f.Desc.Name()))
	}
	sort.Strings(names)
	return strings.Join(names, ", ")
}

// camelTarget proto snake 字段名 → Go 导出字段名（struct 风格的缺省目标）。
func camelTarget(name string) string {
	parts := strings.Split(name, "_")
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(p[1:])
	}
	return b.String()
}

// writeImports 按 goimports 惯例分组输出导入块：标准库一组，其余一组。
func writeImports(b *strings.Builder, qualifiers map[string]string) {
	type imp struct{ qual, path string }
	var std, ext []imp
	for q, p := range qualifiers {
		first := p
		if i := strings.IndexByte(p, '/'); i >= 0 {
			first = p[:i]
		}
		if !strings.Contains(first, ".") {
			std = append(std, imp{q, p})
			continue
		}
		ext = append(ext, imp{q, p})
	}
	sort.Slice(std, func(i, j int) bool { return std[i].path < std[j].path })
	sort.Slice(ext, func(i, j int) bool { return ext[i].path < ext[j].path })

	b.WriteString("import (\n")
	for _, im := range std {
		if im.qual == im.path {
			fmt.Fprintf(b, "\t%q\n", im.path)
		} else {
			fmt.Fprintf(b, "\t%s %q\n", im.qual, im.path)
		}
	}
	if len(std) > 0 && len(ext) > 0 {
		b.WriteString("\n")
	}
	for _, im := range ext {
		fmt.Fprintf(b, "\t%s %q\n", im.qual, im.path)
	}
	b.WriteString(")\n")
}

// writeOptionFunc 生成追加式映射函数：
//
//	func MapXxx(c *v1.Xxx, opts []up.Option) []up.Option
func writeOptionFunc(b *strings.Builder, s *Spec, doc, msgType, targetType string, entries []fieldEntry) {
	writeDoc(b, doc)
	param, appendVar := s.Message.Param, s.Message.Append
	fmt.Fprintf(b, "func %s(%s *%s, %s []%s) []%s {\n",
		s.Message.Func, param, msgType, appendVar, targetType, targetType)

	for _, e := range entries {
		getter := "Get" + e.fld.GoName + "()"
		arg := func(expr string) string {
			if e.spread {
				expr += "..."
			}
			return withCast(e.cast, expr)
		}
		call := func(expr string) string {
			return fmt.Sprintf("\t\t%s = append(%s, %s(%s))\n", appendVar, appendVar, e.target, arg(expr))
		}
		switch e.guard {
		case guardNone:
			fmt.Fprintf(b, "\t%s = append(%s, %s(%s))\n", appendVar, appendVar, e.target, arg(param+"."+getter))
		case guardLen:
			fmt.Fprintf(b, "\tif v := %s.%s; len(v) > 0 {\n", param, getter)
			b.WriteString(call("v"))
			b.WriteString("\t}\n")
		case guardNotNil:
			fmt.Fprintf(b, "\tif v := %s.%s; v != nil {\n", param, getter)
			b.WriteString(call("v"))
			b.WriteString("\t}\n")
		default:
			fmt.Fprintf(b, "\tif v := %s.%s; %s {\n", param, getter, guardCondFor(e))
			b.WriteString(call("v"))
			b.WriteString("\t}\n")
		}
	}

	fmt.Fprintf(b, "\treturn %s\n}\n", appendVar)
}

// guardCondFor 渲染卫语句条件；bool 的 zero 卫语句即 v 本身（true 才应用）。
func guardCondFor(e fieldEntry) string {
	if e.guard == guardZero && e.fld.Desc.Kind() == protoreflect.BoolKind {
		return "v"
	}
	return map[string]string{guardEmpty: `v != ""`, guardZero: "v != 0", guardPositive: "v > 0"}[e.guard]
}

// writeFillFunc 生成填充式映射函数（registry/config 域的
// DefaultConfig + 逐字段覆盖模式）：
//
//	func FillXxx(c *v1.Xxx, cfg *up.Config) *up.Config
func writeFillFunc(b *strings.Builder, s *Spec, doc, msgType, targetType string, entries []fieldEntry) {
	writeDoc(b, doc)
	param, tp := s.Message.Param, s.Message.TargetParam
	fmt.Fprintf(b, "func %s(%s *%s, %s *%s) *%s {\n",
		s.Message.Func, param, msgType, tp, targetType, targetType)

	for _, e := range entries {
		getter := "Get" + e.fld.GoName + "()"
		set := func(expr string) string {
			return fmt.Sprintf("\t\t%s.%s = %s\n", tp, e.target, withCast(e.cast, expr))
		}
		switch e.guard {
		case guardNone:
			fmt.Fprintf(b, "\t%s.%s = %s\n", tp, e.target, withCast(e.cast, param+"."+getter))
		case guardLen:
			fmt.Fprintf(b, "\tif v := %s.%s; len(v) > 0 {\n", param, getter)
			b.WriteString(set("v"))
			b.WriteString("\t}\n")
		case guardNotNil:
			fmt.Fprintf(b, "\tif v := %s.%s; v != nil {\n", param, getter)
			b.WriteString(set("v"))
			b.WriteString("\t}\n")
		default:
			fmt.Fprintf(b, "\tif v := %s.%s; %s {\n", param, getter, guardCondFor(e))
			b.WriteString(set("v"))
			b.WriteString("\t}\n")
		}
	}

	fmt.Fprintf(b, "\treturn %s\n}\n", tp)
}

// writeStructFunc 生成构造式映射函数：
//
//	func NewXxx(c *v1.Xxx) *up.Config
func writeStructFunc(b *strings.Builder, s *Spec, doc, msgType, targetType string, entries []fieldEntry) {
	writeDoc(b, doc)
	param := s.Message.Param
	fmt.Fprintf(b, "func %s(%s *%s) *%s {\n", s.Message.Func, param, msgType, targetType)
	fmt.Fprintf(b, "\treturn &%s{\n", targetType)
	for _, e := range entries {
		getter := "Get" + e.fld.GoName + "()"
		fmt.Fprintf(b, "\t\t%s: %s,\n", e.target, withCast(e.cast, param+"."+getter))
	}
	b.WriteString("\t}\n}\n")
}

// withCast 应用值转换表达式；seconds/millis 借助 time 包常量。
func withCast(cast, expr string) string {
	switch cast {
	case "":
		return expr
	case castSeconds:
		return "time.Duration(" + expr + ") * time.Second"
	case castMillis:
		return "time.Duration(" + expr + ") * time.Millisecond"
	default:
		return cast + "(" + expr + ")"
	}
}

// writeDoc 输出函数文档（spec.comment 优先，缺省取 proto 消息注释）。
func writeDoc(b *strings.Builder, doc string) {
	if doc == "" {
		return
	}
	for _, line := range strings.Split(doc, "\n") {
		line = strings.TrimRight(line, " \t")
		if line == "" {
			b.WriteString("//\n")
			continue
		}
		fmt.Fprintf(b, "// %s\n", line)
	}
}
